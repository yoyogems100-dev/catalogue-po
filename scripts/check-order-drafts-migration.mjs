import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { PGlite } from '@electric-sql/pglite';

// Runs the real migration twice against a disposable in-memory database with
// a stand-in customers table. The live database is not contacted.
const sql = readFileSync(new URL('../supabase/migrations/20261125090000_order_drafts.sql', import.meta.url), 'utf8');
const db = new PGlite();
try {
  await db.exec(`
    create role anon; create role authenticated;
    create table public.customers (id bigint generated by default as identity primary key, name text);
    create table public.orders (id serial primary key);
    insert into public.customers (name) values ('Ravi'), ('Asha');
  `);
  await db.exec(sql);
  await db.query(`insert into public.order_drafts (customer_id, payload) values (1, '{"cart":[{"qty":5}]}'), (null, '{}')`);
  await db.exec(sql);
  assert.equal((await db.query(`select count(*)::int n from public.order_drafts`)).rows[0].n, 2, 'a re-run keeps saved drafts');
  assert.equal((await db.query(`select relrowsecurity from pg_class where relname = 'order_drafts'`)).rows[0].relrowsecurity, true);
  const anon = (await db.query(`select has_table_privilege('anon', 'public.order_drafts', 'select') ok`)).rows[0].ok;
  assert.equal(anon, false, 'anon cannot read drafts');
  await db.exec(`delete from public.customers where id = 1`);
  const row = (await db.query(`select customer_id, payload from public.order_drafts order by id limit 1`)).rows[0];
  assert.equal(row.customer_id, null, 'deleting a buyer keeps the draft');
  assert.equal(row.payload.cart[0].qty, 5);
  assert.equal((await db.query(`select count(*)::int n from public.orders`)).rows[0].n, 0, 'drafts never touch orders');
  console.log('Order drafts migration: table + index, RLS on, anon revoked, repeat-safe, buyer delete keeps draft.');
} finally {
  await db.close();
}
