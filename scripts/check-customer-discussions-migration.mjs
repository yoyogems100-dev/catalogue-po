import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { PGlite } from '@electric-sql/pglite';

// Runs the real migration twice against a disposable in-memory database with
// a stand-in customers table. The live database is not contacted.
const sql = readFileSync(new URL('../supabase/migrations/20261127090000_customer_discussions.sql', import.meta.url), 'utf8');
const db = new PGlite();
try {
  await db.exec(`
    create role anon; create role authenticated;
    create table public.customers (id bigint generated by default as identity primary key, name text);
    insert into public.customers (name) values ('Roshan'), ('Asha');
  `);
  await db.exec(sql);
  await db.query(`insert into public.customer_discussions (customer_id, place, items, notes)
    values (1, 'Jaipur office', '[{"category_id":3,"label":"G Max","details":"White, Canary Yellow"}]', 'Send samples'), (2, 'Phone', '[]', null)`);
  await db.exec(sql);
  assert.equal((await db.query(`select count(*)::int n from public.customer_discussions`)).rows[0].n, 2, 'a re-run keeps saved discussions');
  const row = (await db.query(`select held_on, items from public.customer_discussions where customer_id = 1`)).rows[0];
  assert.ok(row.held_on instanceof Date, 'held_on defaults to today');
  assert.equal(row.items[0].label, 'G Max');
  assert.equal((await db.query(`select relrowsecurity from pg_class where relname = 'customer_discussions'`)).rows[0].relrowsecurity, true);
  assert.equal((await db.query(`select has_table_privilege('anon', 'public.customer_discussions', 'select') ok`)).rows[0].ok, false, 'anon cannot read');
  await assert.rejects(db.query(`insert into public.customer_discussions (customer_id) values (999)`), 'needs a real customer');
  await db.exec(`delete from public.customers where id = 1`);
  assert.equal((await db.query(`select count(*)::int n from public.customer_discussions`)).rows[0].n, 1, 'deleting a buyer removes only their discussions');
  console.log('Customer discussions migration: table + index, RLS on, anon revoked, repeat-safe, cascade on buyer delete.');
} finally {
  await db.close();
}
