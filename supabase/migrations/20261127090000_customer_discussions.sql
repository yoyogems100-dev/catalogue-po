-- Recent discussions: notes from a business call, meeting or exhibition with
-- one buyer. The team writes them in Admin > Customers > Discussions; the
-- buyer reads them (read-only) under My Account > Discussions.
--
-- items is a list of { category_id, label, details } -- the category talked
-- about (label is a snapshot of its name, so a later rename or archive never
-- blanks an old note) and what was discussed under it. notes is free text.
-- place is free text; the suggested list lives in settings
-- 'discussion_places'.
--
-- Deleting a buyer deletes their discussions. No anonymous or signed-in
-- access; only the server (service role) reads and writes it, and the buyer
-- page filters by the signed-in customer. Additive and repeat-safe.

BEGIN;

CREATE TABLE IF NOT EXISTS public.customer_discussions (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id bigint NOT NULL REFERENCES public.customers(id) ON DELETE CASCADE,
  held_on     date NOT NULL DEFAULT CURRENT_DATE,
  place       text,
  items       jsonb NOT NULL DEFAULT '[]'::jsonb,
  notes       text,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS customer_discussions_customer_idx
  ON public.customer_discussions (customer_id, held_on DESC);

ALTER TABLE public.customer_discussions ENABLE ROW LEVEL SECURITY;

DO $$ BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    REVOKE ALL ON public.customer_discussions FROM anon, authenticated;
  END IF;
END $$;

COMMIT;
