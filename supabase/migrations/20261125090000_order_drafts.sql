-- Draft orders: an order the team started building in Admin > New order and
-- saved to finish later. A draft is not an order -- it lives in its own table
-- so no order list, queue, count, customer "My orders", notification or
-- WhatsApp message ever sees it, and it takes no order number. Placing a
-- draft creates a normal order and deletes the draft.
--
-- payload is the builder's own state (customer pick, lines, note, request
-- type, dispatch-from-Jaipur). customer_id is copied out only to list drafts
-- by buyer; ON DELETE SET NULL keeps a draft if that buyer is hard-deleted.
--
-- No anonymous or signed-in access; only the server (service role) reads and
-- writes it. Additive and repeat-safe.

BEGIN;

CREATE TABLE IF NOT EXISTS public.order_drafts (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id bigint REFERENCES public.customers(id) ON DELETE SET NULL,
  payload     jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS order_drafts_updated_at_idx ON public.order_drafts (updated_at DESC);

ALTER TABLE public.order_drafts ENABLE ROW LEVEL SECURITY;

DO $$ BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    REVOKE ALL ON public.order_drafts FROM anon, authenticated;
  END IF;
END $$;

COMMIT;
